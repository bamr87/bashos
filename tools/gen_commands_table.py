#!/usr/bin/env python3
"""Generate the README commands table from the frontmatter of `.claude/commands/*.md`.

    python3 tools/gen_commands_table.py --write    # rewrite the span in README.md
    python3 tools/gen_commands_table.py --check    # exit 1 when the span is stale

Every command file already declares its `description:` and its `bashos.loop`, so the
table between `<!-- AUTO:commands:start -->` and `<!-- AUTO:commands:end -->` in
README.md is derived from them rather than written by hand (UPS-DOC-05). The files
are read through `bashos.registry`, the same parser the kernel routes with, so the
table can never list a command the kernel would not load. tests/test_docs.py fails
when the span is stale.

Needs PyYAML, which bashOS already depends on; runs from the venv or any python3
that has it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = "README.md"
START = "<!-- AUTO:commands:start -->"
END = "<!-- AUTO:commands:end -->"
NOTE = (
    "<!-- GENERATED by `python3 tools/gen_commands_table.py --write` from the frontmatter "
    "of .claude/commands/*.md — do not edit by hand -->"
)


def load_registry(root: Path) -> dict:
    """The command registry, parsed exactly as the kernel parses it."""
    src = str(root / "src")
    if src not in sys.path:
        sys.path.insert(0, src)
    from bashos.registry import load_registry as _load

    return _load(root)


def render(registry: dict) -> str:
    """The span, markers included: one row per command, in name order."""
    rows = ["| command | loop | what it does |", "| --- | --- | --- |"]
    for name in sorted(registry):
        spec = registry[name]
        description = spec.description.replace("|", "\\|")
        rows.append(f"| `/{spec.name}` | `{spec.loop}` | {description} |")
    return "\n".join([START, NOTE, "", *rows, "", END])


def build(root: Path = ROOT) -> tuple[str, str]:
    """Return (README.md as it is, README.md with a freshly rendered span)."""
    text = (root / README).read_text(encoding="utf-8")
    start = text.find(START)
    end = text.find(END, start + len(START)) if start >= 0 else -1
    if start < 0 or end < 0:
        raise SystemExit(f"{README} has no `{START}` … `{END}` span; add the two markers first")
    return text, text[:start] + render(load_registry(root)) + text[end + len(END) :]


def is_current(root: Path = ROOT) -> bool:
    current, fresh = build(root)
    return current == fresh


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="rewrite the span in README.md")
    mode.add_argument("--check", action="store_true", help="exit 1 when the span is stale")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root")
    args = parser.parse_args(argv)

    current, fresh = build(args.root)
    if args.check:
        if current != fresh:
            print(
                f"{README} commands table is stale: run `python3 tools/gen_commands_table.py --write`",
                file=sys.stderr,
            )
            return 1
        return 0
    if current != fresh:
        (args.root / README).write_text(fresh, encoding="utf-8")
        print(f"wrote {README}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
